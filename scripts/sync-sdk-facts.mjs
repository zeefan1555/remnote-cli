#!/usr/bin/env node
/* global console, process, URL */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import prettier from 'prettier';

const target = new URL('../src/remnote-cli/spec/sdk-facts.generated.json', import.meta.url);
const targetTs = new URL('../src/remnote-cli/spec/sdk-facts.generated.ts', import.meta.url);
const check = process.argv.includes('--check');
const sourcePath = process.argv.slice(2).find((value) => !value.startsWith('--'));
if (!sourcePath) {
  console.error('Usage: npm run sync:sdk-facts -- /path/to/sdk-facts.generated.json');
  process.exitCode = 2;
} else {
  const text = await readFile(sourcePath, 'utf8');
  const value = JSON.parse(text);
  if (value.catalogSchemaVersion !== 1) throw new Error('Unsupported SDK facts schema version');
  if (typeof value.sdkVersion !== 'string' || !value.sdkVersion)
    throw new Error('SDK facts sdkVersion is missing');
  if (!Array.isArray(value.capabilities) || value.capabilities.length !== 286)
    throw new Error('SDK facts must contain 286 capabilities');
  const ids = value.capabilities.map((entry) => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry))
      throw new Error('SDK facts capability must be an object');
    const record = entry;
    if (typeof record.id !== 'string' || !record.id)
      throw new Error('SDK facts capability id is missing');
    if ('group' in record || 'command' in record)
      throw new Error('SDK facts must not contain CLI navigation fields');
    return record.id;
  });
  if (new Set(ids).size !== ids.length) throw new Error('SDK facts capability IDs must be unique');
  const hash = createHash('sha256')
    .update(
      JSON.stringify({
        catalogSchemaVersion: value.catalogSchemaVersion,
        sdkVersion: value.sdkVersion,
        capabilities: value.capabilities,
      })
    )
    .digest('hex');
  if (hash !== value.sdkCatalogHash) throw new Error('SDK facts hash does not match its contents');
  const tsContent = await prettier.format(
    '// Generated by scripts/sync-sdk-facts.mjs. Do not edit by hand.\n' +
      `export const SDK_FACTS = ${text.trim()} as const;\n`,
    { ...(await prettier.resolveConfig(targetTs)), parser: 'typescript' }
  );
  if (check) {
    const [currentJson, currentTs] = await Promise.all([
      readFile(target, 'utf8').catch(() => ''),
      readFile(targetTs, 'utf8').catch(() => ''),
    ]);
    if (currentJson !== text || currentTs !== tsContent) {
      console.error('SDK facts are stale. Run npm run sync:sdk-facts -- <source>.');
      process.exitCode = 1;
    }
  } else {
    await Promise.all([writeFile(target, text), writeFile(targetTs, tsContent)]);
    console.log(`Synced ${ids.length} SDK facts for ${value.sdkVersion}`);
  }
}
